/*
 * Builds evidence/RESULTS.md from evidence/walk-*.json. Pure arithmetic over the recorded samples.
 *   bun spikes/004-ios-observation/summarize.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = join(import.meta.dir, 'evidence')
type Walk = {
  transport: string; maestro: string; startupMs: number | null; repeats: number; loadAverageAtEnd: number[]
  chromeIds: string[]
  samples: { step: string; op: string; ms: number; load1: number; passed?: boolean; failure?: string | null }[]
  screens: {
    step: string; marker: string | null; markers: string[]; anchors: string[]; fingerprint: string
    fingerprintWithChrome: string; stable: boolean; unstableReason: string | null; markersInDocumentOrder: string[]; keyboardVisible: boolean; systemUi: string | null
    truncated: boolean; elementCount: number
  }[]
}
const walks = (['process', 'mcp'] as const).filter(name => existsSync(join(dir, `walk-${name}.json`)))
  .map(name => JSON.parse(readFileSync(join(dir, `walk-${name}.json`), 'utf8')) as Walk)

const percentile = (values: number[], p: number) => {
  const sorted = [...values].sort((a, b) => a - b)
  return sorted[Math.min(sorted.length - 1, Math.ceil(p * sorted.length) - 1)]
}
const seconds = (ms: number) => (ms / 1000).toFixed(1)
const lines: string[] = ['# DEJA-18 iOS observation evidence', '', 'Generated by `bun spikes/004-ios-observation/summarize.ts`. Times are seconds.', '']

lines.push('## Step cost', '',
  '| Transport | Maestro | Op | n | failed | median | p90 | min | max | load1 median |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
for (const walk of walks) {
  for (const op of ['observe', 'act', 'reset']) {
    const all = walk.samples.filter(sample => sample.op === op)
    if (all.length === 0) continue
    const ok = all.filter(sample => sample.passed !== false)
    const times = ok.map(sample => sample.ms)
    lines.push(`| ${walk.transport} | ${walk.maestro} | ${op} | ${all.length} | ${all.length - ok.length} | ${seconds(percentile(times, 0.5))} | ${seconds(percentile(times, 0.9))} | ${seconds(Math.min(...times))} | ${seconds(Math.max(...times))} | ${percentile(all.map(sample => sample.load1), 0.5).toFixed(0)} |`)
  }
  if (walk.startupMs !== null) lines.push(`| ${walk.transport} | ${walk.maestro} | session start | 1 | 0 | ${seconds(walk.startupMs)} | | | | |`)
}

lines.push('', '## Load', '',
  'Load average (1 minute) sampled with each step, and the three load averages at the end of each walk:', '')
for (const walk of walks) {
  const loads = walk.samples.map(sample => sample.load1)
  lines.push(`- ${walk.transport}: during the walk min ${Math.min(...loads).toFixed(0)}, median ${percentile(loads, 0.5).toFixed(0)}, max ${Math.max(...loads).toFixed(0)}; at the end ${walk.loadAverageAtEnd.map(value => value.toFixed(0)).join(' / ')}.`)
}

lines.push('', '## Failed steps', '')
const failures = walks.flatMap(walk => walk.samples.filter(sample => sample.passed === false)
  .map(sample => `- ${walk.transport} ${sample.op} \`${sample.step}\`: ${sample.failure ?? 'no detail'}`))
lines.push(...(failures.length ? failures : ['None.']))

const same = (walk: Walk, a: string, b: string) => {
  const left = walk.screens.find(screen => screen.step === a)
  const right = walk.screens.find(screen => screen.step === b)
  if (!left || !right) return 'missing'
  if (!left.stable || !right.stable) {
    const why = [left, right].filter(screen => !screen.stable).map(screen => `${screen.step}: ${screen.unstableReason}`).join('; ')
    return `gap (${why})${left.fingerprint === right.fingerprint ? ', identical hash' : ', hashes differ'}`
  }
  return left.fingerprint === right.fingerprint ? 'same' : 'DIFFERENT'
}
lines.push('', '## Fingerprint stability', '',
  'Fingerprint v2 with `screenMarkerPattern: ^screen\\.`, no chrome IDs. "same" means identical SHA-256.', '',
  '| Transport | Check | Result |', '| --- | --- | --- |')
const checks: [string, string, string][] = [
  ['Today observed twice', 'today#1', 'today#2'],
  ['Feed observed twice', 'feed#1', 'feed#2'],
  ['Journal observed twice', 'journal#1', 'journal#2'],
  ['Today first seen vs seen again after the route', 'today#1', 'today-back#1'],
  ['Today without vs with keyboard (`today.answer`)', 'today-back#1', 'today-keyboard#1'],
  ['Today with keyboard, twice', 'today-keyboard#1', 'today-keyboard#2'],
  ['Today with keyboard vs after it closed', 'today-keyboard#1', 'today-after-keyboard'],
  ['Settings without vs with share sheet (`export.csv`)', 'settings-before-share', 'share-sheet#1'],
  ['Settings before vs after the share sheet', 'settings-before-share', 'settings-after-share'],
]
for (const walk of walks) for (const [label, a, b] of checks) lines.push(`| ${walk.transport} | ${label} | ${same(walk, a, b)} |`)

lines.push('', '## Distinct screens', '',
  'Today, Feed and Journal must have different fingerprints.', '')
for (const walk of walks) {
  const pick = (step: string) => walk.screens.find(screen => screen.step === step)?.fingerprint.slice(0, 12) ?? 'missing'
  lines.push(`- ${walk.transport}: today ${pick('today#1')}, feed ${pick('feed#1')}, journal ${pick('journal#1')}`)
}

lines.push('', '## Normalized IDs per step', '',
  'Markers are IDs matching `^screen\\.`. More than one marker means the hierarchy held another screen.', '')
for (const walk of walks) {
  lines.push(`### ${walk.transport}`, '', '| Step | Markers (document order) | Stable | Anchors | Elements | Keyboard | System UI | Truncated | Fingerprint |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const screen of walk.screens.filter(entry => !entry.step.startsWith('bench'))) {
    lines.push(`| ${screen.step} | ${screen.markersInDocumentOrder.join(', ') || '-'} | ${screen.stable ? 'yes' : screen.unstableReason} | ${screen.anchors.length} | ${screen.elementCount} | ${screen.keyboardVisible} | ${screen.systemUi ?? '-'} | ${screen.truncated} | \`${screen.fingerprint.slice(0, 12)}\` |`)
  }
  lines.push('', `Chrome IDs found across the walk's screens: ${walk.chromeIds.length ? walk.chromeIds.map(id => `\`${id}\``).join(', ') : 'none'}.`, '')
}
writeFileSync(join(dir, 'RESULTS.md'), `${lines.join('\n')}\n`)
console.log(lines.join('\n'))
