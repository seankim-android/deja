#!/usr/bin/env bun
/*
 * Renders docs/results-chart.svg from the saved run reports in demo/live-evidence/.
 * Every number in the chart is read from a report; nothing is typed in by hand.
 * Usage: bun scripts/render-results-chart.ts [--check]
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const repo = resolve(import.meta.dir, '..')
const output = resolve(repo, 'docs/results-chart.svg')

const runs = [
  { label: 'Android cold explore', report: 'android/cold-run-report.json' },
  { label: 'Android warm replay', report: 'android/warm-run-report.json' },
  { label: 'Android stale selector repair', report: 'android/stale-repair-run-report.json' },
  { label: 'Chromium warm replay', report: 'chromium/run-run-report.json' },
]

type Report = { modelCalls: number, durationMs: number, repair?: { durationMs: number } }

const rows = await Promise.all(runs.map(async run => {
  const report: Report = JSON.parse(await readFile(
    resolve(repo, 'demo/live-evidence', run.report), 'utf8'))
  // The README reports the repair step's own duration for the repair run.
  const durationMs = report.repair?.durationMs ?? report.durationMs
  return { ...run, modelCalls: report.modelCalls, seconds: Math.round(durationMs / 100) / 10 }
}))

const width = 820
const top = 100
const rowHeight = 46
const barHeight = 16
const panels = [
  { title: 'Model calls', x: 236, width: 180, max: 15, ticks: [0, 5, 10, 15], value: (r: typeof rows[0]) => r.modelCalls, format: (v: number) => String(v) },
  { title: 'Duration (s)', x: 490, width: 230, max: 100, ticks: [0, 25, 50, 75, 100], value: (r: typeof rows[0]) => r.seconds, format: (v: number) => `${v.toFixed(1)} s` },
]
const plotBottom = top + rows.length * rowHeight
const height = plotBottom + 64

function bar(x: number, y: number, w: number, h: number) {
  // Square at the baseline, 4px rounded data end.
  const r = Math.min(4, w / 2, h / 2)
  if (w <= 0) return ''
  return `M${x},${y}H${x + w - r}Q${x + w},${y} ${x + w},${y + r}V${y + h - r}Q${x + w},${y + h} ${x + w - r},${y + h}H${x}Z`
}

const escape = (text: string) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;')

const parts: string[] = []
parts.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="t d">`)
parts.push(`<title id="t">Déjà run results: model calls and duration</title>`)
parts.push(`<desc id="d">${rows.map(r => `${r.label}: ${r.modelCalls} model calls, ${r.seconds} s`).join('. ')}. Source: demo/live-evidence run reports.</desc>`)
parts.push(`<style>
  .ink { fill: #0b0b0b } .muted { fill: #52514e } .grid { stroke: #a9a8a2 } .axis { stroke: #a9a8a2 } .bar { fill: #2a78d6 }
  text { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif }
  @media (prefers-color-scheme: dark) {
    .ink { fill: #f0efec } .muted { fill: #c3c2b7 } .grid { stroke: #6b6a64 } .axis { stroke: #6b6a64 } .bar { fill: #3987e5 }
  }
</style>`)
parts.push(`<text class="ink" x="0" y="22" font-size="16" font-weight="600">Replay and repair make 0 model calls</text>`)
parts.push(`<text class="muted" x="0" y="46" font-size="12">Saved run reports in demo/live-evidence. Different run types, so durations are not a speedup claim.</text>`)

rows.forEach((row, i) => {
  const y = top + i * rowHeight + rowHeight / 2
  parts.push(`<text class="ink" x="0" y="${y + 4}" font-size="13">${escape(row.label)}</text>`)
})

for (const panel of panels) {
  const scale = (v: number) => (v / panel.max) * panel.width
  parts.push(`<text class="muted" x="${panel.x}" y="${top - 14}" font-size="12" font-weight="600">${panel.title}</text>`)
  for (const tick of panel.ticks) {
    const x = panel.x + scale(tick)
    if (tick === 0) parts.push(`<line class="axis" x1="${x}" x2="${x}" y1="${top}" y2="${plotBottom}" stroke-width="1"/>`)
    else parts.push(`<line class="grid" x1="${x}" x2="${x}" y1="${plotBottom}" y2="${plotBottom + 4}" stroke-width="1"/>`)
    parts.push(`<text class="muted" x="${x}" y="${plotBottom + 18}" font-size="11" text-anchor="middle">${tick}</text>`)
  }
  rows.forEach((row, i) => {
    const value = panel.value(row)
    const y = top + i * rowHeight + (rowHeight - barHeight) / 2
    const w = scale(value)
    if (w > 0) parts.push(`<path class="bar" d="${bar(panel.x, y, w, barHeight)}"/>`)
    parts.push(`<text class="ink" x="${panel.x + w + 6}" y="${y + barHeight / 2 + 4}" font-size="12">${panel.format(value)}</text>`)
  })
}
parts.push(`<text class="muted" x="0" y="${height - 8}" font-size="11">Repair duration is the repair step only. Generated by scripts/render-results-chart.ts.</text>`)
parts.push('</svg>')
const svg = `${parts.join('\n')}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => '')
  if (current !== svg) {
    console.error('docs/results-chart.svg is out of date; run bun scripts/render-results-chart.ts')
    process.exit(1)
  }
  console.log('docs/results-chart.svg matches the run reports')
} else {
  await writeFile(output, svg)
  console.log(JSON.stringify(rows.map(({ label, modelCalls, seconds }) => ({ label, modelCalls, seconds }))))
}
